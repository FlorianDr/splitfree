export async function loader({ request }: Route.LoaderArgs) {
  // siteOrigin is the canonical externally-visible URL (== the WebAuthn RP origin). It feeds the
  // absolute og:url / og:image links so self-hosted instances advertise their own domain. Exposed
  // to every route's meta via `matches` — see ~/lib/meta.
  const siteOrigin = env.WEBAUTHN_ORIGIN;
  const flash = readFlash(request);
  if (flash) return data({ flash, siteOrigin }, { headers: { "Set-Cookie": clearFlashCookie } });
  return { flash: null, siteOrigin };
}

// Default social-card tags for every page; leaf routes override the title via pageMeta (React
// Router replaces — never merges — meta across nested routes).
