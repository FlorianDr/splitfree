export default function App({ loaderData }: Route.ComponentProps) {
  const flash = loaderData?.flash;
  useEffect(() => {
    if (flash) toast[flash.type](flash.message);
  }, [flash]);
  // Register the service worker so the app is installable (and has an offline fallback). The worker
  // never caches authenticated HTML — see public/sw.js.
  useEffect(() => {
    if ("serviceWorker" in navigator) {
      navigator.serviceWorker.register("/sw.js").catch(() => {});
    }
  }, []);
  // When the browser animates a back/forward swipe itself (iOS edge swipe), skip our view
  // transition for that navigation, or the page would animate twice. See the CSS in app.css.
  useEffect(() => {
    const root = document.documentElement;
    let timer: ReturnType<typeof setTimeout> | undefined;
    const onPopState = (event: PopStateEvent) => {
      if (!event.hasUAVisualTransition) return;
      root.dataset.uaTransition = "";
      clearTimeout(timer);
      timer = setTimeout(() => delete root.dataset.uaTransition, 1000);
    };
    // Capture phase, so the flag is set before React Router handles the same popstate.
    addEventListener("popstate", onPopState, { capture: true });
    return () => {
      removeEventListener("popstate", onPopState, { capture: true });
      clearTimeout(timer);
    };
  }, []);
  // The app shell draws its own progress bar under the header; other pages get one at the top.
  const inAppShell = useMatches().some((m) => m.id === "routes/_app");
  return (
    <>
      {inAppShell ? null : (
        <NavigationProgress className="fixed inset-x-0 top-0 z-[100] h-[3px]" />
      )}
      <Outlet />
    </>
  );
}

export function ErrorBoundary({ error }: Route.ErrorBoundaryProps) {
  let message = "Oops!";
  let details = "An unexpected error occurred.";
  let stack: string | undefined;

  if (isRouteErrorResponse(error)) {
    message = error.status === 404 ? "404" : "Error";
    details =
      error.status === 404
        ? "The requested page could not be found."
        : error.statusText || details;
  } else if (import.meta.env.DEV && error && error instanceof Error) {
    details = error.message;
    stack = error.stack;
  }

  return (
    <main className="pt-16 p-4 container mx-auto">
      <h1>{message}</h1>
      <p>{details}</p>
      {stack && (
        <pre className="w-full p-4 overflow-x-auto">
          <code>{stack}</code>
        </pre>
      )}
    </main>
  );
}
